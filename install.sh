#!/usr/bin/env bash
#
# TheOpenTranscribe installer
#
#   curl -fsSL https://raw.githubusercontent.com/AssilAlda/TheOpenTranscribe/main/install.sh | bash
#
# Installs (or updates) TheOpenTranscribe using the prebuilt Docker images
# from GitHub Container Registry. Run the same command again to update.
#
# Optional environment variables:
#   THEOPENTRANSCRIBE_DIR      install folder         (default: ~/theopentranscribe)
#   THEOPENTRANSCRIBE_VERSION  image tag, e.g. 1.0.0  (default: latest)
#   THEOPENTRANSCRIBE_PORT     port on this computer  (default: 3000)
#   THEOPENTRANSCRIBE_NO_OPEN  set to 1 to not open the browser
#
# Everything lives inside main(), which is only called on the very last line,
# so a partially downloaded script never runs.

set -euo pipefail

INSTALL_DIR="${THEOPENTRANSCRIBE_DIR:-$HOME/theopentranscribe}"
VERSION="${THEOPENTRANSCRIBE_VERSION:-latest}"
PORT="${THEOPENTRANSCRIBE_PORT:-3000}"
REPO_URL="https://github.com/AssilAlda/TheOpenTranscribe"

# ---------------------------------------------------------------- output ---

if [ -t 1 ] && [ -z "${NO_COLOR:-}" ]; then
  BOLD=$'\033[1m'; DIM=$'\033[2m'; PINK=$'\033[38;5;204m'
  GREEN=$'\033[32m'; RED=$'\033[31m'; YELLOW=$'\033[33m'; RESET=$'\033[0m'
else
  BOLD=""; DIM=""; PINK=""; GREEN=""; RED=""; YELLOW=""; RESET=""
fi

step() { printf '%s==>%s %s%s%s\n' "$PINK" "$RESET" "$BOLD" "$1" "$RESET"; }
ok()   { printf '    %s✓%s %s\n' "$GREEN" "$RESET" "$1"; }
warn() { printf '    %s!%s %s\n' "$YELLOW" "$RESET" "$1"; }
fail() {
  printf '\n%s✗ %s%s\n' "$RED$BOLD" "$1" "$RESET" >&2
  shift
  for line in "$@"; do printf '  %s\n' "$line" >&2; done
  printf '\n' >&2
  exit 1
}

banner() {
  printf '\n'
  printf '  %s▎▍▌%s  %sTheOpenTranscribe%s\n' "$PINK" "$RESET" "$BOLD" "$RESET"
  printf '       %sSelf-hosted audio & video transcription%s\n\n' "$DIM" "$RESET"
}

# ---------------------------------------------------------------- checks ---

check_docker() {
  step "Checking Docker"

  if ! command -v docker >/dev/null 2>&1; then
    case "$(uname -s)" in
      Darwin) hint="Install Docker Desktop (https://www.docker.com/products/docker-desktop) or OrbStack (https://orbstack.dev), open it, then run this command again." ;;
      Linux)  hint="Install Docker Engine: https://docs.docker.com/engine/install — then run this command again." ;;
      *)      hint="Install Docker Desktop: https://www.docker.com/products/docker-desktop — then run this command again." ;;
    esac
    fail "Docker is not installed." "$hint"
  fi

  if ! docker info >/dev/null 2>&1; then
    fail "Docker is installed but not running." \
      "Open Docker Desktop (or OrbStack) and wait until it says it's running," \
      "then run this command again." \
      "Using Colima? Run: colima start && docker context use colima"
  fi

  if ! docker compose version >/dev/null 2>&1; then
    fail "Docker Compose is missing." \
      "Docker Desktop and OrbStack include it. On Linux, install the plugin:" \
      "https://docs.docker.com/compose/install/linux/"
  fi

  ok "Docker $(docker version --format '{{.Server.Version}}' 2>/dev/null || echo '') is running"
}

# ----------------------------------------------------------------- files ---

write_compose_file() {
  # Same services as the repository's docker-compose.yml, but using the
  # prebuilt release images instead of building from source.
  cat > "$INSTALL_DIR/docker-compose.yml" <<'EOF'
# Generated by the TheOpenTranscribe installer. Re-running the installer
# overwrites this file; put your own settings in .env instead.
name: theopentranscribe

services:
  web:
    image: ghcr.io/assilalda/theopentranscribe-web:${THEOPENTRANSCRIBE_VERSION:-latest}
    # Only reachable from this computer by default (the app has no login).
    ports:
      - "${THEOPENTRANSCRIBE_BIND:-127.0.0.1}:${THEOPENTRANSCRIBE_PORT:-3000}:3000"
    environment:
      DATA_DIR: /data
      THEOPENTRANSCRIBE_CONFIG_DIR: /config
      OPENAI_API_KEY: ${OPENAI_API_KEY:-}
      THEOPENTRANSCRIBE_TRUSTED_ORIGINS: ${THEOPENTRANSCRIBE_TRUSTED_ORIGINS:-}
    volumes:
      - data_dir:/data
      - config_dir:/config
    restart: unless-stopped

  runner:
    image: ghcr.io/assilalda/theopentranscribe-runner:${THEOPENTRANSCRIBE_VERSION:-latest}
    environment:
      DATA_DIR: /data
      THEOPENTRANSCRIBE_CONFIG_DIR: /config
      OPENAI_API_KEY: ${OPENAI_API_KEY:-}
      RUNNER_POLL_INTERVAL_MS: ${RUNNER_POLL_INTERVAL_MS:-}
    volumes:
      - data_dir:/data
      - config_dir:/config
    restart: unless-stopped
    stop_grace_period: 600s

volumes:
  data_dir:
  config_dir:
EOF
}

write_env_file() {
  local env_file="$INSTALL_DIR/.env"
  if [ -f "$env_file" ]; then
    ok "Kept your existing settings (.env)"
    return
  fi
  cat > "$env_file" <<EOF
# TheOpenTranscribe settings. Run the installer again after changing them.

# Image version to run: "latest" or a release such as "1.0.0".
THEOPENTRANSCRIBE_VERSION=$VERSION

# Port on this computer: the app opens at http://localhost:<port>
THEOPENTRANSCRIBE_PORT=$PORT

# Optional: your OpenAI API key. Easier: add it in the app under Provider.
OPENAI_API_KEY=

# Optional: set to 0.0.0.0 to allow other devices on your network.
# The app has no login -- anyone who can reach it can use your API key.
# Then also add the address you browse from below, for example
# THEOPENTRANSCRIBE_TRUSTED_ORIGINS=http://192.168.1.50:3000
THEOPENTRANSCRIBE_BIND=
THEOPENTRANSCRIBE_TRUSTED_ORIGINS=
EOF
  chmod 600 "$env_file"
  ok "Created settings file"
}

setup_files() {
  step "Preparing $INSTALL_DIR"
  mkdir -p "$INSTALL_DIR"
  write_compose_file
  ok "Wrote docker-compose.yml"
  write_env_file

  # Explicit env vars win over .env, so `THEOPENTRANSCRIBE_VERSION=1.0.0`
  # on the command line also updates the saved setting.
  if [ -n "${THEOPENTRANSCRIBE_VERSION:-}" ]; then set_env_value THEOPENTRANSCRIBE_VERSION "$VERSION"; fi
  if [ -n "${THEOPENTRANSCRIBE_PORT:-}" ]; then set_env_value THEOPENTRANSCRIBE_PORT "$PORT"; fi

  # Read the port actually in effect, for the health check and final message.
  local saved_port
  saved_port="$(sed -n 's/^THEOPENTRANSCRIBE_PORT=\([0-9][0-9]*\)$/\1/p' "$INSTALL_DIR/.env" | tail -1)"
  PORT="${saved_port:-3000}"
}

set_env_value() {
  local key="$1" value="$2" env_file="$INSTALL_DIR/.env" tmp
  tmp="$(mktemp)"
  if grep -q "^$key=" "$env_file"; then
    sed "s|^$key=.*|$key=$value|" "$env_file" > "$tmp"
  else
    cat "$env_file" > "$tmp"
    printf '%s=%s\n' "$key" "$value" >> "$tmp"
  fi
  cat "$tmp" > "$env_file"
  rm -f "$tmp"
}

compose() { docker compose --project-directory "$INSTALL_DIR" "$@" </dev/null; }

# ----------------------------------------------------------------- start ---

start_app() {
  step "Downloading the app (first time can take a minute)"
  if ! compose pull --quiet; then
    fail "Could not download the app images." \
      "Check your internet connection and try again." \
      "If it keeps failing, please open an issue: $REPO_URL/issues"
  fi
  ok "Images are up to date"

  step "Starting TheOpenTranscribe"
  local log
  log="$(mktemp)"
  if ! compose up -d --remove-orphans --quiet-pull 2>"$log"; then
    if grep -qiE 'port is already allocated|address already in use' "$log"; then
      fail "Port $PORT is already used by another program." \
        "Pick another port, for example:" \
        "curl -fsSL https://raw.githubusercontent.com/AssilAlda/TheOpenTranscribe/main/install.sh | THEOPENTRANSCRIBE_PORT=3001 bash"
    fi
    cat "$log" >&2
    rm -f "$log"
    fail "The app could not be started." "See the error above, or open an issue: $REPO_URL/issues"
  fi
  rm -f "$log"
  ok "Containers started"

  step "Waiting for the app to be ready"
  local url="http://localhost:$PORT/api/health" _
  for _ in $(seq 1 60); do
    if curl -fsS -o /dev/null "$url" 2>/dev/null; then
      ok "The app is up"
      return
    fi
    sleep 2
  done
  fail "The app did not respond within 2 minutes." \
    "See what went wrong with:  cd $INSTALL_DIR && docker compose logs"
}

open_browser() {
  [ "${THEOPENTRANSCRIBE_NO_OPEN:-}" = "1" ] && return 0
  local url="http://localhost:$PORT"
  if command -v open >/dev/null 2>&1; then open "$url" >/dev/null 2>&1 || true
  elif command -v xdg-open >/dev/null 2>&1; then xdg-open "$url" >/dev/null 2>&1 || true
  fi
}

print_done() {
  local url="http://localhost:$PORT"
  printf '\n'
  printf '  %s╭──────────────────────────────────────────────────────╮%s\n' "$PINK" "$RESET"
  printf '  %s│%s  %s✓ TheOpenTranscribe is running%s                      %s│%s\n' "$PINK" "$RESET" "$GREEN$BOLD" "$RESET" "$PINK" "$RESET"
  printf '  %s│%s                                                      %s│%s\n' "$PINK" "$RESET" "$PINK" "$RESET"
  printf '  %s│%s  Open  %s%-46s%s%s│%s\n' "$PINK" "$RESET" "$BOLD" "$url" "$RESET" "$PINK" "$RESET"
  printf '  %s╰──────────────────────────────────────────────────────╯%s\n' "$PINK" "$RESET"
  printf '\n'
  printf '  %sNext:%s click %sProvider%s, paste your OpenAI API key, then upload a file.\n' "$BOLD" "$RESET" "$BOLD" "$RESET"
  printf '  %sNo key yet? Create one at https://platform.openai.com/api-keys%s\n\n' "$DIM" "$RESET"
  printf '  %sStop%s     cd %s && docker compose down\n' "$BOLD" "$RESET" "$INSTALL_DIR"
  printf '  %sStart%s    cd %s && docker compose up -d\n' "$BOLD" "$RESET" "$INSTALL_DIR"
  printf '  %sUpdate%s   run the install command again\n\n' "$BOLD" "$RESET"
}

main() {
  banner
  command -v curl >/dev/null 2>&1 || fail "curl is required but not installed."
  check_docker
  setup_files
  start_app
  open_browser
  print_done
}

main "$@"
